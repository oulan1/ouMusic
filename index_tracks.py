def infer_genres(artist_name, title):
    name = (artist_name or '').lower()
    for key, genres in ARTIST_GENRES.items():
        if key in name:
            return genres
    return ['Pop', 'Electronic', 'Indie']


def index_playlists(catalog):
    base_dir = os.path.dirname(os.path.abspath(__file__))
    playlists_dir = os.path.join(base_dir, 'playlists')

    if not os.path.exists(playlists_dir):
        os.makedirs(playlists_dir, exist_ok=True)

    catalog_ids = {t["id"] for t in catalog}
    playlists = []
    files = sorted(os.listdir(playlists_dir))

    for filename in files:
        if not (filename.lower().endswith('.oulist') or filename.lower().endswith('.json')):
            continue
        if filename in ('playlists.json', 'playlists.js', 'catalog.json', 'catalog.js'):
            continue

        filepath = os.path.join(playlists_dir, filename)
        try:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = json.load(f)
        except Exception as e:
            print(f"[Warn] Could not parse playlist {filename}: {e}")
            continue

        pl_info = data.get('playlist', {})
        pl_name = pl_info.get('name') or data.get('name') or os.path.splitext(filename)[0]
        pl_id = pl_info.get('id') or data.get('id') or ('pl_' + os.path.splitext(filename)[0])
        pl_desc = pl_info.get('description') or data.get('description') or 'Пользовательский плейлист сообщества ouMusic'
        pl_author = pl_info.get('author') or pl_info.get('creator') or data.get('author') or 'Пользователь ouMusic'
        pl_cover = pl_info.get('coverBase64') or data.get('coverBase64') or None

        raw_tracks = data.get('tracks', [])
        raw_track_ids = data.get('trackIds', [])
        if not raw_track_ids and raw_tracks:
            raw_track_ids = [t.get('id') for t in raw_tracks if isinstance(t, dict) and t.get('id')]

        # Strictly filter only tracks that exist in the site catalog (no missing local tracks!)
        filtered_ids = [tid for tid in raw_track_ids if tid in catalog_ids]

        playlists.append({
            "id": pl_id,
            "filename": filename,
            "name": pl_name,
            "description": pl_desc,
            "author": pl_author,
            "coverBase64": pl_cover,
            "trackIds": filtered_ids,
            "trackCount": len(filtered_ids)
        })

    # 1. Write playlists/playlists.json
    json_path = os.path.join(playlists_dir, 'playlists.json')
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(playlists, f, ensure_ascii=False, indent=2)

    # 2. Write playlists/playlists.js
    js_path = os.path.join(playlists_dir, 'playlists.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by index_tracks.py. Do not edit manually. */\n")
        f.write("window.__SHARED_PLAYLISTS__ = ")
        json.dump(playlists, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"[ouMusic] Indexed {len(playlists)} shared playlist(s) successfully.")
    for pl in playlists:
        print(f"  [Playlist] {pl['name']} by {pl['author']} ({pl['trackCount']} available tracks)")

def index_tracks():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    tracks_dir = os.path.join(base_dir, 'tracks')

    if not os.path.exists(tracks_dir):
        os.makedirs(tracks_dir, exist_ok=True)

    catalog = []
    files = sorted(os.listdir(tracks_dir))

    for filename in files:
        if not filename.lower().endswith('.oump3'):
            continue

        filepath = os.path.join(tracks_dir, filename)
        stats = os.stat(filepath)
        mod_time = datetime.fromtimestamp(stats.st_mtime, timezone.utc).isoformat()

        meta = {}
        try:
            with zipfile.ZipFile(filepath, 'r') as zf:
                if 'header.json' in zf.namelist():
                    meta = json.loads(zf.read('header.json').decode('utf-8'))
        except Exception as e:
            print(f"[Warn] Could not read header.json from {filename}: {e}")

        raw_name = filename[:-6]
        default_artist = "Неизвестный исполнитель"
        default_title = raw_name

        if " - " in raw_name:
            parts = raw_name.split(" - ", 1)
            default_artist = parts[0].strip()
            default_title = parts[1].strip()

        track_id = meta.get('id')
        if not track_id:
            track_id = raw_name.lower().replace(' ', '_').replace('-', '_')
            while '__' in track_id:
                track_id = track_id.replace('__', '_')
            track_id = track_id.strip('_')

        is_explicit = meta.get('isExplicit', meta.get('explicit', False))
        has_instrumental = meta.get('hasInstrumental', False)
        instrumental_config = meta.get('instrumentalConfig', None)
        thumb_base64 = meta.get('thumbBase64', None)

        entry = {
            "id": track_id,
            "filename": filename,
            "title": meta.get('title', default_title),
            "artist": meta.get('artist', default_artist),
            "genres": meta.get('genres') if (meta.get('genres') and len(meta.get('genres')) > 0) else infer_genres(meta.get('artist', default_artist), meta.get('title', default_title)),
            "duration": meta.get('duration', 0),
            "hasLyrics": meta.get('hasLyrics', True),
            "isExplicit": bool(is_explicit),
            "explicit": bool(is_explicit),
            "hasInstrumental": bool(has_instrumental),
            "instrumentalConfig": instrumental_config,
            "thumbBase64": thumb_base64,
            "size": stats.st_size,
            "updatedAt": mod_time
        }
        catalog.append(entry)

    # Sort deterministically by filename
    catalog.sort(key=lambda x: x["filename"].lower())

    # 1. Write tracks/catalog.json
    json_path = os.path.join(tracks_dir, 'catalog.json')
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    # 2. Write tracks/catalog.js (for file:// fallback without CORS errors)
    js_path = os.path.join(tracks_dir, 'catalog.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by index_tracks.py. Do not edit manually. */\n")
        f.write("window.__TRACKS_CATALOG__ = ")
        json.dump(catalog, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    index_playlists(catalog)
    print(f"[ouMusic] Indexed {len(catalog)} track(s) successfully.")
    for t in catalog:
        print(f"  - {t['artist']} — {t['title']} ({t['duration']}s, explicit={t['isExplicit']}, inst={t['hasInstrumental']})")

if __name__ == '__main__':
    index_tracks()
