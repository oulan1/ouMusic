#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ouMusic Tracks Auto-Indexer
Scans tracks/*.oump3, preserves existing remote/CDN tracks from tracks/catalog.json,
extracts full metadata (title, artist, genres, duration, cover thumbnail, lyrics flag,
explicit tag, instrumental DSP config, storage repo, jsDelivr CDN and fallback URLs),
and generates tracks/catalog.json and tracks/catalog.js.
"""

import os
import sys
import re
import urllib.parse
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass
import json
import zipfile
from datetime import datetime, timezone


# Known Artist Genre Database for intelligent inference
ARTIST_GENRES = {
    'sqwore': ['Hyperpop', 'Glitchcore', 'Emo Rap'],
    'серега пират': ['Phonk', 'Meme Rap', 'Indie'],
    'serega pirat': ['Phonk', 'Meme Rap', 'Indie'],
    'imagine dragons': ['Alt Rock', 'Pop Rock', 'Indie'],
    'shadowraze': ['Phonk', 'Dota Rap', 'Underground'],
    'три дня дождя': ['Rock', 'Post-Punk', 'Indie'],
    'kizaru': ['Trap', 'Hip-Hop', 'Cloud Rap'],
    'big baby tape': ['Trap', 'Hip-Hop', 'Rap'],
    'og buda': ['Trap', 'Hip-Hop', 'Detroit Rap'],
    'pharaoh': ['Cloud Rap', 'Hip-Hop', 'Emo Rap'],
    'macan': ['Hip-Hop', 'Pop Rap', 'Lyric'],
    'miyagi': ['Reggae', 'Hip-Hop', 'Soul'],
    'saluki': ['Hip-Hop', 'Indie Rap', 'Alternative']
}

def infer_genres(artist_name, title):
    name = (artist_name or '').lower()
    for key, genres in ARTIST_GENRES.items():
        if key in name:
            return genres
    return ['Pop', 'Electronic', 'Indie']


def index_playlists(catalog):
    base_dir = os.path.dirname(os.path.abspath(__file__))
    playlists_dir = os.path.join(base_dir, 'playlists')

    if not os.path.exists(playlists_dir):
        os.makedirs(playlists_dir, exist_ok=True)

    catalog_ids = {t["id"] for t in catalog}
    playlists = []
    files = sorted(os.listdir(playlists_dir))

    for filename in files:
        if not (filename.lower().endswith('.oulist') or filename.lower().endswith('.json')):
            continue
        if filename in ('playlists.json', 'playlists.js', 'catalog.json', 'catalog.js'):
            continue

        filepath = os.path.join(playlists_dir, filename)
        try:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = json.load(f)
        except Exception as e:
            print(f"[Warn] Could not parse playlist {filename}: {e}")
            continue

        pl_info = data.get('playlist', {})
        pl_name = pl_info.get('name') or data.get('name') or os.path.splitext(filename)[0]
        pl_id = pl_info.get('id') or data.get('id') or ('pl_' + os.path.splitext(filename)[0])
        pl_desc = pl_info.get('description') or data.get('description') or 'Пользовательский плейлист сообщества ouMusic'
        pl_author = pl_info.get('author') or pl_info.get('creator') or data.get('author') or 'Пользователь ouMusic'
        pl_cover = pl_info.get('coverBase64') or data.get('coverBase64') or None

        raw_tracks = data.get('tracks', [])
        raw_track_ids = data.get('trackIds', [])
        if not raw_track_ids and raw_tracks:
            raw_track_ids = [t.get('id') for t in raw_tracks if isinstance(t, dict) and t.get('id')]

        # Strictly filter only tracks that exist in the site catalog
        filtered_ids = [tid for tid in raw_track_ids if tid in catalog_ids]

        playlists.append({
            "id": pl_id,
            "filename": filename,
            "name": pl_name,
            "description": pl_desc,
            "author": pl_author,
            "coverBase64": pl_cover,
            "trackIds": filtered_ids,
            "trackCount": len(filtered_ids)
        })

    # 1. Write playlists/playlists.json
    json_path = os.path.join(playlists_dir, 'playlists.json')
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(playlists, f, ensure_ascii=False, indent=2)

    # 2. Write playlists/playlists.js
    js_path = os.path.join(playlists_dir, 'playlists.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by index_tracks.py. Do not edit manually. */\n")
        f.write("window.__SHARED_PLAYLISTS__ = ")
        json.dump(playlists, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"[ouMusic] Indexed {len(playlists)} shared playlist(s) successfully.")
    for pl in playlists:
        print(f"  [Playlist] {pl['name']} by {pl['author']} ({pl['trackCount']} available tracks)")


def index_tracks():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    tracks_dir = os.path.join(base_dir, 'tracks')

    if not os.path.exists(tracks_dir):
        os.makedirs(tracks_dir, exist_ok=True)

    json_path = os.path.join(tracks_dir, 'catalog.json')
    catalog_map = {}

    # 1. Load existing catalog to preserve remote/CDN tracks and their metadata
    if os.path.exists(json_path):
        try:
            with open(json_path, 'r', encoding='utf-8') as f:
                existing_catalog = json.load(f)
                if isinstance(existing_catalog, list):
                    for item in existing_catalog:
                        if isinstance(item, dict) and item.get('id'):
                            catalog_map[item['id']] = item
        except Exception as e:
            print(f"[Warn] Could not read existing catalog.json: {e}")

    # 2. Scan local tracks/ for .oump3 files (if any exist locally)
    files = sorted(os.listdir(tracks_dir))
    for filename in files:
        if not filename.lower().endswith('.oump3'):
            continue

        filepath = os.path.join(tracks_dir, filename)
        stats = os.stat(filepath)
        mod_time = datetime.fromtimestamp(stats.st_mtime, timezone.utc).isoformat()

        meta = {}
        has_studio_inst = False
        try:
            with zipfile.ZipFile(filepath, 'r') as zf:
                namelist = zf.namelist()
                if 'header.json' in namelist:
                    meta = json.loads(zf.read('header.json').decode('utf-8'))
                has_studio_inst = any('instrumental.' in n.lower() for n in namelist)
        except Exception as e:
            print(f"[Warn] Could not read header.json from {filename}: {e}")

        raw_name = filename[:-6]
        default_artist = "Неизвестный исполнитель"
        default_title = raw_name

        if " - " in raw_name:
            parts = raw_name.split(" - ", 1)
            default_artist = parts[0].strip()
            default_title = parts[1].strip()

        track_id = meta.get('id')
        if not track_id:
            track_id = raw_name.lower().replace(' ', '_').replace('-', '_')
            while '__' in track_id:
                track_id = track_id.replace('__', '_')
            track_id = track_id.strip('_')

        is_explicit = meta.get('isExplicit', meta.get('explicit', False))
        has_instrumental = meta.get('hasInstrumental', False) or has_studio_inst
        has_studio_instrumental = bool(meta.get('hasStudioInstrumental', False) or has_studio_inst)
        instrumental_config = meta.get('instrumentalConfig', None)
        thumb_base64 = meta.get('thumbBase64', None)
        ai_fact = meta.get('aiFact', '')

        entry_genres = meta.get('genres') if (meta.get('genres') and len(meta.get('genres')) > 0) else infer_genres(meta.get('artist', default_artist), meta.get('title', default_title))

        categories = meta.get('categories')
        if not categories:
            categories = []
            text = f"{default_artist} {default_title}".lower()
            if bool(re.search(r'[а-яА-ЯёЁ]', text)):
                categories.append('lang:ru')
            else:
                categories.append('lang:en')
            cur_genres = [g.lower() for g in entry_genres]
            if any(x in ' '.join(cur_genres) for x in ['hyperpop', 'phonk', 'trap', 'rock', 'electronic']):
                categories.append('mood:energy')
            elif any(x in ' '.join(cur_genres) for x in ['emo rap', 'post-punk', 'indie', 'melancholy']):
                categories.append('mood:melancholy')
            else:
                categories.append('mood:energy')

        # Existing entry if already in catalog
        existing_entry = catalog_map.get(track_id, {})

        entry = {
            "id": track_id,
            "filename": filename,
            "title": meta.get('title', default_title),
            "artist": meta.get('artist', default_artist),
            "genres": entry_genres,
            "categories": categories,
            "duration": meta.get('duration', existing_entry.get('duration', 0)),
            "hasLyrics": meta.get('hasLyrics', True),
            "isExplicit": bool(is_explicit),
            "explicit": bool(is_explicit),
            "hasInstrumental": bool(has_instrumental),
            "hasStudioInstrumental": bool(has_studio_instrumental),
            "instrumentalConfig": instrumental_config or existing_entry.get('instrumentalConfig'),
            "aiFact": ai_fact or existing_entry.get('aiFact', ''),
            "thumbBase64": thumb_base64 or existing_entry.get('thumbBase64'),
            "size": stats.st_size,
            "updatedAt": mod_time
        }

        # Preserve remote CDN / fallback metadata if present
        if 'storageRepo' in existing_entry:
            entry['storageRepo'] = existing_entry['storageRepo']
        if 'cdnUrl' in existing_entry:
            entry['cdnUrl'] = existing_entry['cdnUrl']
        if 'fallbackUrl' in existing_entry:
            entry['fallbackUrl'] = existing_entry['fallbackUrl']

        catalog_map[track_id] = entry

    # 3. Ensure all tracks have valid CDN and fallback URLs if a storageRepo is specified
    for tid, entry in catalog_map.items():
        storage_repo = entry.get('storageRepo')
        filename = entry.get('filename')
        if storage_repo and filename:
            enc_name = urllib.parse.quote(filename)
            if not entry.get('cdnUrl'):
                entry['cdnUrl'] = f"https://cdn.jsdelivr.net/gh/{storage_repo}@main/tracks/{enc_name}"
            if not entry.get('fallbackUrl'):
                entry['fallbackUrl'] = f"https://raw.githubusercontent.com/{storage_repo}/main/tracks/{enc_name}"

    # 4. Sort catalog deterministically (by artist + title)
    catalog = sorted(
        catalog_map.values(),
        key=lambda x: (x.get("artist", "") + " - " + x.get("title", "")).lower()
    )

    # 5. Write tracks/catalog.json
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    # 6. Write tracks/catalog.js (for file:// protocol fallback without CORS errors)
    js_path = os.path.join(tracks_dir, 'catalog.js')
    with open(js_path, 'w', encoding='utf-8') as f:
        f.write("/* Auto-generated by index_tracks.py. Do not edit manually. */\n")
        f.write("window.__TRACKS_CATALOG__ = ")
        json.dump(catalog, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    index_playlists(catalog)
    print(f"[ouMusic] Indexed {len(catalog)} track(s) successfully.")
    for t in catalog:
        storage_info = f" [CDN: {t.get('storageRepo')}]" if t.get('storageRepo') else " [Local]"
        print(f"  - {t['artist']} — {t['title']} ({t['duration']}s, explicit={t['isExplicit']}, inst={t['hasInstrumental']}){storage_info}")

if __name__ == '__main__':
    index_tracks()
